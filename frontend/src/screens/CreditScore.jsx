/**
 * Screen 8: Kirana Credit Score
 * Multi-factor score with factor breakdown + exportable one-pager
 */
import { useEffect, useState } from 'react';
import { getCreditScore } from '../api/client';

export default function CreditScore() {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    getCreditScore().then(d => { setData(d); setLoading(false); }).catch(() => setLoading(false));
  }, []);

  const tierConfig = {
    PRIME: { color: 'var(--signal-green)', label: 'Prime', emoji: '🌟' },
    STANDARD: { color: 'var(--signal-blue)', label: 'Standard', emoji: '✅' },
    SUBPRIME: { color: 'var(--signal-amber)', label: 'Sub-prime', emoji: '⚠️' },
    HIGH_RISK: { color: 'var(--signal-red)', label: 'High Risk', emoji: '🚨' },
  };

  const tier = data ? (tierConfig[data.tier] || tierConfig.STANDARD) : null;

  const handleExport = () => {
    if (!data) return;
    const content = `
KIRANA CREDIT SCORE — LENDER REPORT
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Store: ${data.storeName}
Score: ${data.score}/100 (${data.tier})
Generated: ${new Date(data.computedAt).toLocaleString('en-IN')}
Framework: India Account Aggregator (RBI/Sahamati)

SCORE BREAKDOWN:
${Object.values(data.factors).map(f =>
  `  ${f.label.padEnd(30)} ${f.score}/100  (Weight: ${f.weight}%)`
).join('\n')}

ESTIMATED CREDIT LIMIT: ₹${data.maxCreditLimitEstimate.toLocaleString('en-IN')}

${data.aaFrameworkNote}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Generated by Shelf2Cash — shelf2cash.app
    `.trim();
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = `kirana-credit-score-${data.merchantId}.txt`;
    a.click(); URL.revokeObjectURL(url);
  };

  if (loading) return <div className="screen"><div className="skeleton" style={{ height: 300 }} /></div>;

  return (
    <div className="screen" style={{ display: 'flex', flexDirection: 'column', gap: 'var(--space-md)' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
        <div>
          <h1 style={{ fontFamily: 'var(--font-heading)', fontSize: '1.25rem', fontWeight: 700, marginBottom: 4 }}>Kirana Credit Score</h1>
          <p style={{ fontSize: '0.8125rem', color: 'var(--text-secondary)' }}>Lender-ready financial profile</p>
        </div>
        <button className="btn btn-sm btn-ghost" onClick={handleExport}>⬇ Export</button>
      </div>

      {/* Score hero */}
      <div className="card" style={{
        background: 'var(--bg-card)',
        border: `1px solid ${tier?.color}40`,
        boxShadow: `0 0 40px ${tier?.color}20`
      }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: 'var(--space-lg)', marginBottom: 'var(--space-md)' }}>
          <div style={{
            width: 80, height: 80, borderRadius: '50%',
            background: `${tier?.color}20`, border: `3px solid ${tier?.color}`,
            display: 'flex', alignItems: 'center', justifyContent: 'center',
            flexDirection: 'column', gap: 2
          }}>
            <span style={{ fontFamily: 'var(--font-heading)', fontSize: '1.5rem', fontWeight: 800, color: tier?.color, lineHeight: 1 }}>
              {data?.score}
            </span>
            <span style={{ fontSize: '0.55rem', color: tier?.color, fontWeight: 600 }}>/100</span>
          </div>
          <div>
            <div style={{ fontSize: '1.25rem', fontWeight: 700 }}>{tier?.emoji} {tier?.label}</div>
            <div style={{ color: 'var(--text-secondary)', fontSize: '0.875rem' }}>{data?.storeName}</div>
            <div style={{ fontSize: '0.75rem', color: 'var(--text-muted)', marginTop: 4 }}>
              Est. credit limit: <strong style={{ color: tier?.color }}>₹{data?.maxCreditLimitEstimate.toLocaleString('en-IN')}</strong>
            </div>
          </div>
        </div>
        <div className="alert-banner info" style={{ fontSize: '0.75rem' }}>
          🏛 Based on India's Account Aggregator (RBI/Sahamati) framework — ready for lender API sharing
        </div>
      </div>

      {/* Factor breakdown */}
      <div className="card">
        <p style={{ fontSize: '0.75rem', color: 'var(--text-muted)', marginBottom: 12, textTransform: 'uppercase', letterSpacing: '0.05em' }}>
          Score Factors
        </p>
        {data?.factors && Object.values(data.factors).map(factor => (
          <div key={factor.label} style={{ marginBottom: 14 }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: 4, alignItems: 'flex-end' }}>
              <div>
                <span style={{ fontWeight: 600, fontSize: '0.875rem' }}>{factor.label}</span>
                <span style={{ marginLeft: 6, fontSize: '0.7rem', color: 'var(--text-muted)' }}>Weight: {factor.weight}%</span>
              </div>
              <span style={{ fontWeight: 700, color:
                factor.score >= 70 ? 'var(--signal-green)' :
                factor.score >= 50 ? 'var(--signal-amber)' : 'var(--signal-red)'
              }}>{factor.score}/100</span>
            </div>
            <div className="progress-bar">
              <div className="progress-fill" style={{
                width: `${factor.score}%`,
                background: factor.score >= 70 ? 'var(--signal-green)' :
                             factor.score >= 50 ? 'var(--signal-amber)' : 'var(--signal-red)'
              }} />
            </div>
            <div style={{ fontSize: '0.75rem', color: 'var(--text-muted)', marginTop: 3 }}>{factor.detail}</div>
            <div style={{ fontSize: '0.65rem', color: 'var(--brand-primary)', marginTop: 2 }}>AA: {factor.aaFramework}</div>
          </div>
        ))}
      </div>

      <button className="btn btn-primary btn-full" onClick={handleExport}>
        ⬇ Download Lender One-Pager
      </button>
    </div>
  );
}
